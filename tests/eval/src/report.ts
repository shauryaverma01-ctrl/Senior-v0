// Report writer — emits scorecard.csv (machine-readable) and report.html
// (self-contained, demo-ready). HTML uses inline CSS only and <details> for
// collapse, no external assets — safe to open in any browser, including offline.

import type { Rubric, RunResult, ScenarioResult } from "./types.ts";

export async function writeReport(
  runDir: string,
  run: RunResult,
  rubric: Rubric,
  baseline?: RunResult,
): Promise<void> {
  await Deno.writeTextFile(`${runDir}/scorecard.csv`, buildCsv(run, rubric));
  await Deno.writeTextFile(`${runDir}/report.html`, buildHtml(run, rubric, baseline));
}

// ─── CSV ─────────────────────────────────────────────────────────────────────

function buildCsv(run: RunResult, rubric: Rubric): string {
  const headerCols = [
    "scenario_id",
    "category",
    "overall_pass",
    "overall_percent",
    "end_reason",
    "tool_calls",
    "duration_ms",
    ...rubric.dimensions.map((d) => `${d.id}_score`),
    ...rubric.dimensions.map((d) => `${d.id}_max`),
  ];
  const lines = [headerCols.join(",")];
  for (const r of run.results) {
    const dimensionScores = rubric.dimensions.map((d) =>
      r.scores.find((s) => s.id === d.id)?.score ?? 0
    );
    const dimensionMaxes = rubric.dimensions.map((d) => d.max);
    const row = [
      csvEscape(r.scenario.id),
      csvEscape(r.scenario.category),
      r.overall_pass ? "true" : "false",
      String(r.overall_percent),
      csvEscape(r.transcript.end_reason),
      String(r.transcript.tool_calls.length),
      String(r.duration_ms),
      ...dimensionScores.map(String),
      ...dimensionMaxes.map(String),
    ];
    lines.push(row.join(","));
  }
  return lines.join("\n") + "\n";
}

function csvEscape(s: string): string {
  if (s.includes(",") || s.includes('"') || s.includes("\n")) {
    return `"${s.replace(/"/g, '""')}"`;
  }
  return s;
}

// ─── HTML ────────────────────────────────────────────────────────────────────

function buildHtml(run: RunResult, rubric: Rubric, baseline?: RunResult): string {
  const passCount = run.results.filter((r) => r.overall_pass).length;
  const failCount = run.results.length - passCount;
  const dimensionAverages = computeDimensionAverages(run, rubric);
  const baselineDelta = baseline
    ? `${run.pass_rate - baseline.pass_rate >= 0 ? "+" : ""}${run.pass_rate - baseline.pass_rate}pp vs ${baseline.run_id}`
    : "";

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>DeepCall Eval — ${escapeHtml(run.run_id)}</title>
<meta name="viewport" content="width=device-width, initial-scale=1" />
<style>${INLINE_CSS}</style>
</head>
<body>
<header>
  <div class="brand">
    <span class="brand-dot"></span>
    <span class="brand-name">DeepCall</span>
    <span class="brand-sub">Voice-agent evaluation</span>
  </div>
  <div class="meta">
    <div><strong>Run</strong> ${escapeHtml(run.run_id)}</div>
    <div><strong>Prompt</strong> <code>${escapeHtml(run.prompt_path)}</code> @ <code>${run.prompt_sha256.slice(0, 12)}</code></div>
    <div><strong>Subject</strong> Maya — Blue Door Cafe, Khan Market</div>
  </div>
</header>

<section class="cards">
  <div class="card pass">
    <div class="card-label">Pass rate</div>
    <div class="card-value">${run.pass_rate}<span class="unit">%</span></div>
    <div class="card-sub">${passCount} pass · ${failCount} fail · ${run.scenarios_run} total ${baselineDelta ? `· ${escapeHtml(baselineDelta)}` : ""}</div>
  </div>
  <div class="card">
    <div class="card-label">Started</div>
    <div class="card-value small">${escapeHtml(run.started_at.replace("T", " ").slice(0, 19))}</div>
    <div class="card-sub">UTC</div>
  </div>
  <div class="card">
    <div class="card-label">Threshold</div>
    <div class="card-value small">${rubric.pass_threshold.min_overall_percent}%</div>
    <div class="card-sub">all critical dimensions must pass</div>
  </div>
</section>

<section>
  <h2>Dimension averages</h2>
  <table class="dimension-table">
    <thead>
      <tr><th>Dimension</th><th>Avg score</th><th>Bar</th><th>Critical</th></tr>
    </thead>
    <tbody>
      ${dimensionAverages.map((d) => `
        <tr>
          <td>${escapeHtml(d.label)}</td>
          <td class="num">${d.avg.toFixed(2)} / ${d.max}</td>
          <td><div class="bar"><div class="bar-fill" style="width:${(d.avg / d.max * 100).toFixed(0)}%"></div></div></td>
          <td>${d.critical ? '<span class="pill crit">critical</span>' : '<span class="pill">scoring</span>'}</td>
        </tr>
      `).join("")}
    </tbody>
  </table>
</section>

<section>
  <h2>Scenarios (${run.results.length})</h2>
  ${run.results.map((r) => renderScenarioCard(r, baseline)).join("\n")}
</section>

<footer>
  <p>Generated by Senior eval harness · <code>tests/eval/src/runner.ts</code> · ${escapeHtml(run.ended_at)}</p>
  <p>This report is self-contained — no external CSS or JS. Safe to email or open offline.</p>
</footer>
</body>
</html>
`;
}

function renderScenarioCard(r: ScenarioResult, baseline?: RunResult): string {
  const baseR = baseline?.results.find((b) => b.scenario.id === r.scenario.id);
  const delta = baseR ? r.overall_percent - baseR.overall_percent : null;
  const deltaText = delta === null ? "" : `<span class="delta ${delta >= 0 ? "up" : "down"}">${delta >= 0 ? "+" : ""}${delta}pp</span>`;
  const statusClass = r.overall_pass ? "ok" : "fail";

  return `<details class="scenario ${statusClass}">
  <summary>
    <span class="status-pill ${statusClass}">${r.overall_pass ? "PASS" : "FAIL"}</span>
    <code class="sid">${escapeHtml(r.scenario.id)}</code>
    <span class="cat">${escapeHtml(r.scenario.category)}</span>
    <span class="desc">${escapeHtml(r.scenario.description)}</span>
    <span class="pct">${r.overall_percent}%</span>
    ${deltaText}
  </summary>
  <div class="scenario-body">
    <p class="judge-summary">${escapeHtml(r.judge_summary)}</p>
    <table class="dim-mini">
      <tbody>
        ${r.scores.map((s) => `
          <tr class="${s.score >= s.max ? "ok" : (s.critical ? "crit-fail" : "soft-fail")}">
            <td class="dim-label">${escapeHtml(s.label)}</td>
            <td class="dim-score">${s.score} / ${s.max}</td>
            <td class="dim-reason">${escapeHtml(s.reasoning)}</td>
          </tr>
        `).join("")}
      </tbody>
    </table>
    <details class="transcript">
      <summary>Transcript (${r.transcript.turns.length} turns · end=${r.transcript.end_reason}${r.transcript.emitted_intent ? ` · intent=${r.transcript.emitted_intent}` : ""})</summary>
      <div class="turns">
        ${r.transcript.turns.map(renderTurn).join("")}
      </div>
    </details>
  </div>
</details>`;
}

function renderTurn(t: { role: string; content: string; tool_call?: { name: string; args: Record<string, unknown> } }): string {
  if (t.role === "tool_result") {
    const name = t.tool_call?.name ?? "tool";
    const args = t.tool_call ? JSON.stringify(t.tool_call.args) : "{}";
    return `<div class="turn tool"><span class="role">[${escapeHtml(name)}]</span> <span class="args">${escapeHtml(args)}</span> → <span class="result">${escapeHtml(t.content)}</span></div>`;
  }
  const cls = t.role === "maya" ? "maya" : "customer";
  return `<div class="turn ${cls}"><span class="role">${t.role.toUpperCase()}</span><span class="text">${escapeHtml(t.content)}</span></div>`;
}

function computeDimensionAverages(run: RunResult, rubric: Rubric): Array<{
  id: string;
  label: string;
  avg: number;
  max: number;
  critical: boolean;
}> {
  return rubric.dimensions.map((d) => {
    const scores = run.results.map((r) => r.scores.find((s) => s.id === d.id)?.score ?? 0);
    const avg = scores.length === 0 ? 0 : scores.reduce((a, b) => a + b, 0) / scores.length;
    return { id: d.id, label: d.label, avg, max: d.max, critical: d.critical };
  });
}

function escapeHtml(s: string | undefined): string {
  if (s === undefined || s === null) return "";
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

